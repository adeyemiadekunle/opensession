"""
Per-user egress allowlists.

Every running sandbox has its own Docker network with its own subnet, and the
egress proxy (Squid) sees requests coming from that subnet. So a user's extra
domains are applied with one rule per sandbox network:

    acl u1_src src 172.23.0.0/16
    acl u1_dst dstdomain .example.com api.other.dev
    http_access allow u1_src u1_dst

The file is written into a volume shared with the proxy (EGRESS_CONF_DIR, mounted
at /etc/squid/conf.d in the proxy) and the proxy is told to reload. The proxy's
main config denies internal addresses before these rules, so a user domain that
resolves to an internal IP is still refused.
"""

from __future__ import annotations

import asyncio
import ipaddress
import logging
import os
from typing import Any

from .userstore import UserStore

log = logging.getLogger("opensession.egress")
RULES_FILE = "50-users.conf"


def render_rules(networks: list[tuple[str, str]], domains: dict[str, list[str]]) -> str:
    """networks: (user, subnet) for each running sandbox; domains: user -> domains."""
    lines = ["# Generated by the OpenSession gateway. Do not edit.", ""]
    n = 0
    for user, subnet in sorted(networks):
        doms = domains.get(user) or []
        if not doms:
            continue
        try:
            net = ipaddress.ip_network(subnet, strict=False)
        except ValueError:
            continue
        n += 1
        lines.append(f"# user {user}")
        lines.append(f"acl u{n}_src src {net}")
        lines.append(f"acl u{n}_dst dstdomain {' '.join(doms)}")
        lines.append(f"http_access allow u{n}_src u{n}_dst")
        lines.append("")
    return "\n".join(lines) + "\n"


class EgressRules:
    def __init__(
        self,
        users: UserStore,
        manager: Any,
        conf_dir: str | None,
        proxy_container: str | None,
        global_allowlist_path: str | None = None,
        extra_domains: list[str] | None = None,
    ):
        self.users = users
        self.manager = manager
        self.conf_dir = conf_dir
        self.proxy_container = proxy_container
        self.global_allowlist_path = global_allowlist_path
        # Allowed for every sandbox on top of the static allowlist (e.g. OpenCode's hosted models).
        self.extra_domains = list(extra_domains or [])
        self._lock = asyncio.Lock()
        self.last_rendered: str | None = None

    @classmethod
    def from_env(cls, users: UserStore, manager: Any) -> "EgressRules":
        e = os.environ.get
        return cls(
            users,
            manager,
            e("EGRESS_CONF_DIR") or None,
            e("SANDBOX_EGRESS_PROXY") or None,
            e("EGRESS_GLOBAL_ALLOWLIST") or None,
            # ALLOW_OPENCODE_PROVIDER=1 offers OpenCode's own (free) models: its inference lives at opencode.ai.
            [".opencode.ai"] if e("ALLOW_OPENCODE_PROVIDER", "0") == "1" else [],
        )

    @property
    def enabled(self) -> bool:
        return bool(self.conf_dir and self.proxy_container)

    def global_domains(self) -> list[str]:
        if not self.global_allowlist_path:
            return []
        try:
            with open(self.global_allowlist_path) as f:
                return [l.strip() for l in f if l.strip() and not l.lstrip().startswith("#")]
        except OSError:
            return []

    async def sync(self) -> None:
        """Rewrite the per-user rules from the running sandbox networks and reload the proxy."""
        if not self.enabled:
            return
        async with self._lock:
            networks = await asyncio.to_thread(self.manager.user_networks)
            users = {u for u, _ in networks}
            domains = await asyncio.to_thread(self.users.domains_for_users, users)
            if self.extra_domains:
                domains = {u: [*(domains.get(u) or []), *self.extra_domains] for u in users}
            text = render_rules(networks, domains)
            if text == self.last_rendered:
                return
            path = os.path.join(self.conf_dir, RULES_FILE)
            tmp = path + ".tmp"
            await asyncio.to_thread(_write, tmp, text)
            await asyncio.to_thread(os.replace, tmp, path)
            ok = await asyncio.to_thread(self.manager.exec_in, self.proxy_container, ["squid", "-k", "reconfigure"])
            if ok:
                self.last_rendered = text
            else:
                log.warning("egress proxy reload failed; will retry on next change")


def _write(path: str, text: str) -> None:
    with open(path, "w") as f:
        f.write(text)
    os.chmod(path, 0o644)
